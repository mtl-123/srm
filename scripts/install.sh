#!/usr/bin/env bash
set -euo pipefail
project="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
binary="$project/target/release/srm"
[[ ! -x "$project/srm" ]] || binary="$project/srm"
replace_rm=false
activate_bash=false
enable_timer=false
activate_zsh=false
while (($#)); do
    case "$1" in
        --binary) binary="${2:?--binary requires a file}"; shift 2 ;;
        --replace-rm) replace_rm=true; shift ;;
        --activate-bash) activate_bash=true; shift ;;
        --activate-zsh) activate_zsh=true; shift ;;
        --enable-upload-timer) enable_timer=true; shift ;;
        *) printf 'Unknown option: %s\n' "$1" >&2; exit 1 ;;
    esac
done
[[ $EUID != 0 ]] || { echo "Use scripts/install-system.sh for root/system installation." >&2; exit 1; }
[[ "$HOME" = /* && -n "$HOME" && "$HOME" != / ]] || { echo 'HOME must be an absolute user directory' >&2; exit 1; }
[[ -x "$binary" ]] || { echo 'Build with cargo build --release first, or use --binary FILE' >&2; exit 1; }
if ! "$binary" --version; then
    echo "Cannot execute binary; use the x86_64-unknown-linux-musl static package." >&2
    exit 1
fi
destination="$HOME/.local/lib/safe-srm"
bin_dir="$HOME/.local/bin"
config="$HOME/.config/safe-srm"
for name in srm $($replace_rm && printf rm || true); do
    link="$bin_dir/$name"
    if [[ -e "$link" || -L "$link" ]]; then
        [[ -L "$link" && "$(readlink -- "$link")" = "$destination/srm" ]] || {
            printf 'Refusing to overwrite an unrelated command: %s\n' "$link" >&2; exit 1;
        }
    fi
done
mkdir -p -- "$destination" "$bin_dir" "$config"
mkdir -p -- "$HOME/.local/share/bash-completion/completions" "$HOME/.local/share/zsh/site-functions"
install -m 0644 "$project/completions/srm.bash" "$HOME/.local/share/bash-completion/completions/srm"
zsh_source="$project/_srm"
[[ -f "$zsh_source" ]] || zsh_source="$project/completions/_srm"
install -m 0644 "$zsh_source" "$HOME/.local/share/zsh/site-functions/_srm"
install -m 0644 "$project/completions/completion_ids.py" "$destination/completion_ids.py"
install -m 0755 -- "$binary" "$destination/srm.new"
mv -f -- "$destination/srm.new" "$destination/srm"
ln -sfn -- "$destination/srm" "$bin_dir/srm"
if $replace_rm; then
    ln -sfn -- "$destination/srm" "$bin_dir/rm"
fi
{
    printf '# Generated by safe-srm installer. Absolute /bin/rm remains native.\n'
    printf 'export PATH=%q:"$PATH"\n' "$bin_dir"
    printf 'if [[ -n ${BASH_VERSION:-} && $- == *i* ]]; then source %q; fi\n' "$HOME/.local/share/bash-completion/completions/srm"
    if $replace_rm; then
        # A function also takes precedence over existing PATH order and aliases.
        printf 'unalias rm 2>/dev/null || true\n'
        printf 'rm() { %q --rm "$@"; }\n' "$destination/srm"
    fi
} > "$config/env.sh"
{
    printf '# Generated srm-only Zsh completion activation\n'
    printf 'fpath=(%q $fpath)\n' "$HOME/.local/share/zsh/site-functions"
    printf 'autoload -Uz compinit\n(( $+functions[compdef] )) || compinit\n'
    printf 'autoload -Uz _srm\ncompdef _srm srm\n'
} > "$config/completion.zsh"
if $activate_zsh && ! grep -Fq '# safe-srm completion activation' "$HOME/.zshrc" 2>/dev/null; then
    [[ ! -e "$HOME/.zshrc" ]] || cp -p -- "$HOME/.zshrc" "$HOME/.zshrc.before-safe-srm.$(date +%s)"
    printf '\n# safe-srm completion activation\n[[ ! -f %q ]] || source %q\n' "$config/completion.zsh" "$config/completion.zsh" >> "$HOME/.zshrc"
fi
if $activate_bash; then
    if ! grep -Fq '# safe-srm managed activation' "$HOME/.bashrc" 2>/dev/null; then
        if [[ -e "$HOME/.bashrc" ]]; then
            cp -p -- "$HOME/.bashrc" "$HOME/.bashrc.before-safe-srm.$(date +%s)"
        fi
        {
            printf '\n# safe-srm managed activation\n'
            printf '[[ ! -f %q ]] || source %q\n' "$config/env.sh" "$config/env.sh"
        } >> "$HOME/.bashrc"
    fi
fi
printf 'Installed: %s\n' "$destination/srm"
settings_file="${SRM_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/safe-srm/config.json}"
if [[ ! -e "$settings_file" ]]; then "$destination/srm" --config "$settings_file" config --init; fi
if $enable_timer; then
    mkdir -p -- "$HOME/.config/systemd/user"
    install -m 0644 "$project/systemd/safe-srm-upload.service" "$HOME/.config/systemd/user/"
    install -m 0644 "$project/systemd/safe-srm-upload.timer" "$HOME/.config/systemd/user/"
    systemctl --user daemon-reload
    systemctl --user enable --now safe-srm-upload.timer
fi
printf 'Activate in this shell: source %q\n' "$config/env.sh"
printf 'Permanent deletion escape: /bin/rm -- FILE\n'
printf 'User installation only. For sudo use scripts/install-system.sh, then sudo /usr/local/bin/srm.\n'
if ! "$destination/srm" --config "$settings_file" doctor >/dev/null; then
    printf 'Storage needs attention. For user-owned directories with broad permissions: srm doctor --repair-permissions\n' >&2
    exit 1
fi
